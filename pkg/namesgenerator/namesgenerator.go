// GetRandomName generates a random name formatted as "adjective_name".
// If retry is greater than zero, a random digit between 0 and 9 is appended.
func GetRandomName(retry int) string {
	name := adjectives[rand.Intn(len(adjectives))] + "_" + names[rand.Intn(len(names))] //nolint:gosec // weak RNG is fine for display names
	if retry > 0 {
		name += strconv.Itoa(rand.Intn(10)) //nolint:gosec // weak RNG is fine for display names
	}
	return name
}
